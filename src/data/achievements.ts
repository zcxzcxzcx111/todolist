// 获取稀有度颜色
export function getRarityColor(rarity: Achievement['rarity']): string {
  switch (rarity) {
    case 'common': return '#8E8E93';
    case 'rare': return '#007AFF';
    case 'epic': return '#9B59B6';
    case 'legendary': return '#FFD700';
    default: return '#8E8E93';
  }
}

// 获取稀有度名称
export function getRarityName(rarity: Achievement['rarity']): string {
  switch (rarity) {
    case 'common': return '普通';
    case 'rare': return '稀有';
    case 'epic': return '史诗';
    case 'legendary': return '传说';
    default: return '普通';
  }
}

// 获取分类名称
export function getCategoryName(category: Achievement['category']): string {
  switch (category) {
    case 'travel': return '旅行';
    case 'task': return '任务';
    case 'pomodoro': return '番茄钟';
    case 'streak': return '连续打卡';
    case 'special': return '特殊';
    case 'collection': return '收集';
    default: return '其他';
  }
}
