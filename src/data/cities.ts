// 获取从当前城市到下一个城市的距离
export function getNextCityMiles(currentCityId: string, visitedCityIds: string[]): { city: City; miles: number } | null {
  const currentCity = cities.find(c => c.id === currentCityId);
  if (!currentCity) return null;

  const currentIdx = cities.findIndex(c => c.id === currentCityId);
  const nextCity = cities.find((c, i) => i > currentIdx && !visitedCityIds.includes(c.id));

  if (!nextCity) return null;

  const miles = cityDistances[currentCityId]?.[nextCity.id] || nextCity.requiredMiles;
  return { city: nextCity, miles };
}
